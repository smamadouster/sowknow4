# Lines before the first recognised section header.
PREAMBLE_SECTION = "Preamble"

_HEADING_RE = re.compile(r"^#{1,6}\s+(.*?)\s*#*\s*$")

# Section names are matched case-insensitively against the FR4.2.2 set.
_SECTION_NAMES = {s.lower(): s for s in SECTIONS}


def split_summary_sections(summary_md: str) -> dict[str, list[str]]:
    """Split a summary into its FR4.2.2 sections (Overview / Key Findings /
    Trends & Patterns / Notable Anomalies / Supporting Data).

    Content before the first recognised header is reported under
    "Preamble". Unrecognised headings stay inside the current section.
    Returns {section_name: [lines]} in document order.
    """
    sections: dict[str, list[str]] = {}
    current: str | None = None
    for line in (summary_md or "").splitlines():
        heading = _HEADING_RE.match(line.strip())
        name = _SECTION_NAMES.get(heading.group(1).lower()) if heading else None
        if name is not None:
            current = name
            sections.setdefault(current, [])
            continue
        if current is None:
            current = PREAMBLE_SECTION
            sections.setdefault(current, [])
        sections[current].append(line)
    return sections


def diff_disclosures(
    disclosures_from: list[dict[str, Any]] | None,
    disclosures_to: list[dict[str, Any]] | None,
) -> dict[str, Any]:
    """Compare two disclosure lists keyed on their ``type``: added types,
    removed types, and types present in both whose payload changed."""
    def _by_type(disclosures):
        result: dict[str, dict[str, Any]] = {}
        for disclosure in disclosures or []:
            if isinstance(disclosure, dict):
                result[str(disclosure.get("type") or "unknown")] = disclosure
        return result

    old = _by_type(disclosures_from)
    new = _by_type(disclosures_to)
    return {
        "added": [new[t] for t in new if t not in old],
        "removed": [old[t] for t in old if t not in new],
        "changed": [new[t] for t in new if t in old and new[t] != old[t]],
    }


def diff_deliverables(deliverable_from: Any, deliverable_to: Any) -> dict[str, Any]:
    """FR5.5: per-section unified diff of two deliverable versions.

    Sections missing on one side are reported as added/removed; identical
    sections as unchanged (with an empty diff).
    """
    import difflib

    sections_from = split_summary_sections(
        getattr(deliverable_from, "summary_md", None) or ""
    )
    sections_to = split_summary_sections(
        getattr(deliverable_to, "summary_md", None) or ""
    )

    ordered_names = [PREAMBLE_SECTION, *SECTIONS]
    extras = [
        name for name in (*sections_from, *sections_to)
        if name not in ordered_names
    ]
    section_diffs: list[dict[str, Any]] = []
    for name in [*ordered_names, *dict.fromkeys(extras)]:
        old = sections_from.get(name)
        new = sections_to.get(name)
        if old is None and new is None:
            continue
        if old is None:
            status, diff = "added", []
        elif new is None:
            status, diff = "removed", []
        elif old == new:
            status, diff = "unchanged", []
        else:
            status = "changed"
            diff = list(difflib.unified_diff(
                old, new,
                fromfile=f"v{getattr(deliverable_from, 'version', '?')}",
                tofile=f"v{getattr(deliverable_to, 'version', '?')}",
                lineterm="",
            ))
        section_diffs.append({"section": name, "status": status, "diff": diff})

    return {
        "from_version": getattr(deliverable_from, "version", None),
        "to_version": getattr(deliverable_to, "version", None),
        "sections": section_diffs,
        "disclosures": diff_disclosures(
            getattr(deliverable_from, "disclosures", None),
            getattr(deliverable_to, "disclosures", None),
        ),
    }
