"""Packaging Service — FR5 in-app view assembly and PDF export.

- FR5.1/FR5.4  ``build_in_app_view``: summary + ranked, annotated item list
               (deep links ``/documents/{document_id}``) + appendix with
               analysis tables. Charts are built ONLY from computed analysis
               outputs (Vega-Lite specs via the smart_folder chart_generator);
               nothing is ever drawn from raw LLM prose.
- FR5.6        ``export_pdf``: reportlab export following the collections.py
               pattern — header with request params summary, generation
               timestamp (UTC) and data-as-of date; disclosures are listed
               BEFORE the item list; every page footer reads
               "Generated by SOWKNOW Collection · <timestamp> · data as of <date>".
- FR5.2        ``export_docx``: python-docx Word export with the same
               content blocks as the PDF (header/footer info, disclosures,
               summary, item list, appendix tables).
- FR5.3        Citation links are internal URIs (``/documents/{id}``); the
               frontend re-checks permission at navigation. The deliverable
               JSON records this as ``links_permission_bound: true``.
"""

