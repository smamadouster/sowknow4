def _item_view(item: dict[str, Any]) -> dict[str, Any]:
    document_id = item.get("document_id")
    return {
        "id": str(item.get("id")) if item.get("id") else None,
        "document_id": str(document_id) if document_id else None,
        "title": item.get("title"),
        "annotation": item.get("annotation") or item.get("annotation_text"),
        "category_tags": item.get("category_tags") or [],
        "date": _iso(item.get("item_date") or item.get("date")),
        "source": item.get("source"),
        "author": item.get("author"),
        "snippet": item.get("snippet"),
        "rank_position": item.get("rank_position"),
        "relevance_score": item.get("relevance_score"),
        "status": item.get("status") or "ok",
        "page_number": item.get("page_number"),
        # FR5.3 — internal deep link; permission re-checked at navigation.
        "link": f"/documents/{document_id}" if document_id else None,
        "related_items": [
            {
                "id": str(dup.get("id")) if dup.get("id") else None,
                "document_id": str(dup.get("document_id")) if dup.get("document_id") else None,
                "title": dup.get("title"),
                "link": f"/documents/{dup.get('document_id')}" if dup.get("document_id") else None,
            }
            for dup in item.get("related_items") or []
        ],
    }


def _iso(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


def _analysis_appendix(analyses: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Tables from computed outputs; charts only from computed series."""
    appendix: list[dict[str, Any]] = []
    for analysis in analyses or []:
        analysis_type = analysis.get("analysis_type")
        output = analysis.get("output") or {}
        entry: dict[str, Any] = {
            "analysis_type": analysis_type,
            "tables": [],
            "charts": [],
            "messages": [],
        }

        if analysis_type == "descriptive":
            rows = [
                {
                    "metric": m.get("metric"),
                    "unit": m.get("unit"),
                    "count": m.get("count"),
                    "total": m.get("total"),
                    "mean": m.get("mean"),
                    "min": m.get("min"),
                    "max": m.get("max"),
                }
                for m in output.get("metrics") or []
            ]
            if rows:
                entry["tables"].append({
                    "title": "Descriptive statistics",
                    "columns": ["metric", "unit", "count", "total", "mean", "min", "max"],
                    "rows": rows,
                })

        elif analysis_type == "trend":
            table_rows = []
            for trend in output.get("trends") or []:
                if not trend.get("sufficient_data"):
                    entry["messages"].append(
                        f"{trend.get('metric')}: {trend.get('message', 'insufficient data')}"
                    )
                    continue
                table_rows.append({
                    "metric": trend.get("metric"),
                    "unit": trend.get("unit"),
                    "direction": trend.get("direction"),
                    "slope": trend.get("slope"),
                })
                points = [
                    {"period": str(p.get("period")), "value": p.get("value")}
                    for p in trend.get("points") or []
                    if p.get("value") is not None
                ]
                if len(points) >= 2:
                    # Chart built strictly from computed trend points.
                    entry["charts"].append(chart_generator.line_chart(
                        points,
                        x_field="period",
                        y_field="value",
                        title=f"{trend.get('metric')} trend",
                    ))
            if table_rows:
                entry["tables"].append({
                    "title": "Trends",
                    "columns": ["metric", "unit", "direction", "slope"],
                    "rows": table_rows,
                })

        elif analysis_type == "anomaly":
            table_rows = []
            for metric in output.get("metrics") or []:
                if not metric.get("sufficient_data"):
                    entry["messages"].append(
                        f"{metric.get('metric')}: {metric.get('message', 'insufficient data')}"
                    )
                    continue
                for anomaly in metric.get("anomalies") or []:
                    table_rows.append({
                        "metric": metric.get("metric"),
                        "value": anomaly.get("value"),
                        "date": anomaly.get("date"),
                        "rules": ", ".join(anomaly.get("rules") or []),
                        "z_score": anomaly.get("z_score"),
                    })
            if table_rows:
                entry["tables"].append({
                    "title": "Anomalies",
                    "columns": ["metric", "value", "date", "rules", "z_score"],
                    "rows": table_rows,
                })

        elif analysis_type == "comparison":
            if not output.get("sufficient_data"):
                entry["messages"].append(output.get("message", "insufficient data"))
            for comparison in output.get("comparisons") or []:
                title = comparison.get("family") or f"Comparison ({comparison.get('unit') or 'no unit'})"
                entry["tables"].append({
                    "title": f"Ranking — {title}",
                    "columns": ["rank", "label", "count", "total", "mean"],
                    "rows": comparison.get("ranking") or [],
                })
                pairwise = comparison.get("pairwise") or []
                if pairwise:
                    entry["tables"].append({
                        "title": f"Pairwise differences — {title}",
                        "columns": ["a", "b", "total_difference", "mean_difference"],
                        "rows": pairwise,
                    })

        elif analysis_type == "correlation":
            if not output.get("sufficient_data"):
                message = output.get("message", "insufficient data")
                best = output.get("best_observed")
                if best:
                    message += (
                        f" (best observed: {best.get('metric_a')} vs "
                        f"{best.get('metric_b')}, r = {best.get('r')}, "
                        f"n = {best.get('n')})"
                    )
                entry["messages"].append(message)
            correlations = output.get("correlations") or []
            if correlations:
                entry["tables"].append({
                    "title": "Correlations (association, not causation)",
                    "columns": ["metric_a", "metric_b", "n", "r", "p_value"],
                    "rows": correlations,
                })

        elif output.get("message"):
            entry["messages"].append(output["message"])

        appendix.append(entry)
    return appendix


def build_in_app_view(
    deliverable: Any,
    items_with_annotations: list[dict[str, Any]],
    analyses: list[dict[str, Any]],
) -> dict[str, Any]:
    """FR5.1: summary + ranked item list + appendix, all permission-bound.

    FR7.2: every user-content field (summary, titles, snippets,
    annotations) is sanitised before rendering — filenames and chunk text
    are attacker-controllable.
    """
    sorted_items = sorted(
        items_with_annotations,
        key=lambda it: (it.get("rank_position") is None, it.get("rank_position") or 0),
    )
    dates = [
        _iso(it.get("item_date") or it.get("date"))
        for it in items_with_annotations
    ]
    dates = [d for d in dates if d]
    return {
        "deliverable_id": str(getattr(deliverable, "id", "")),
        "request_id": str(getattr(deliverable, "request_id", "")),
        "version": getattr(deliverable, "version", 1),
        "summary_md": sanitise_text(getattr(deliverable, "summary_md", None)),
        "items": [sanitise_item(_item_view(it)) for it in sorted_items],
        "appendix": {
            **(getattr(deliverable, "appendix", None) or {}),
            "analyses_rendered": _analysis_appendix(analyses),
        },
        "disclosures": getattr(deliverable, "disclosures", None) or [],
        "data_as_of": max(dates) if dates else None,
        "generated_at": _iso(getattr(deliverable, "created_at", None)),
        # FR5.3 — every link is an internal URI; the frontend re-checks
        # permission when the user navigates.
        "links_permission_bound": True,
    }


