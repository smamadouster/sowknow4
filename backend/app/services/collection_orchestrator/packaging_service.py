def _md_to_blocks(md: str) -> list[tuple[str, str]]:
    """Minimal markdown → (kind, text) blocks; inline markers stripped."""
    blocks: list[tuple[str, str]] = []
    for line in (md or "").splitlines():
        stripped = line.strip()
        if not stripped or stripped == "---":
            continue
        heading = _MD_HEADING_RE.match(stripped)
        text = _MD_BOLD_RE.sub(r"\1", stripped)
        text = _MD_ITALIC_RE.sub(r"\1", text)
        if heading:
            blocks.append(("heading", text))
        elif _MD_BULLET_RE.match(stripped):
            blocks.append(("bullet", _MD_BULLET_RE.sub("", text)))
        else:
            blocks.append(("para", text))
    return blocks


def export_docx(deliverable: Any, view: dict[str, Any]) -> bytes:
    """FR5.2: Word (.docx) export — same content as the PDF: FR5.6 header
    info block and page footer, disclosures BEFORE the item list, summary
    sections, item table and appendix analysis tables.

    FR7.2: the view is sanitised first (idempotent)."""
    view = sanitise_view(view)
    from docx import Document as DocxDocument

    generated_at = datetime.now(timezone.utc)
    generated_str = generated_at.strftime("%Y-%m-%d %H:%M UTC")
    data_as_of = (view.get("data_as_of") or "unknown")[:10]
    footer_text = (
        f"Generated by SOWKNOW Collection · {generated_str} · data as of {data_as_of}"
    )

    doc = DocxDocument()

    # ── Header: request params summary, timestamps (FR5.6) ───────────────
    doc.add_heading("SOWKNOW Collection Deliverable", level=0)
    doc.add_paragraph(f"Generated {generated_str} · Data as of {data_as_of}")
    doc.add_paragraph(
        f"Deliverable v{view.get('version', 1)} · "
        f"{len(view.get('items') or [])} item(s) · "
        "Links are permission-bound (re-checked at navigation)."
    )
    appendix = view.get("appendix") or {}
    if appendix.get("request_params"):
        doc.add_paragraph(f"Request: {appendix['request_params']}")

    # ── Disclosures BEFORE the item list (FR5.6) ─────────────────────────
    disclosures = view.get("disclosures") or []
    if disclosures:
        doc.add_heading("Disclosures", level=1)
        for disclosure in disclosures:
            doc.add_paragraph(_disclosure_text(disclosure), style="List Bullet")

    # ── Summary ──────────────────────────────────────────────────────────
    if view.get("summary_md"):
        doc.add_heading("Summary", level=1)
        for kind, text in _md_to_blocks(view["summary_md"]):
            if kind == "heading":
                doc.add_heading(text, level=2)
            elif kind == "bullet":
                doc.add_paragraph(text, style="List Bullet")
            else:
                doc.add_paragraph(text)

    # ── Item list ────────────────────────────────────────────────────────
    items = view.get("items") or []
    if items:
        doc.add_heading("Source Items", level=1)
        table = doc.add_table(rows=1, cols=4)
        table.style = "Table Grid"
        for index, header in enumerate(["#", "Title", "Date", "Annotation"]):
            table.rows[0].cells[index].text = header
        for item in items:
            cells = table.add_row().cells
            cells[0].text = str(item.get("rank_position") or "—")
            cells[1].text = (item.get("title") or "untitled")[:60]
            cells[2].text = (item.get("date") or "—")[:10]
            cells[3].text = (item.get("annotation") or "")[:180]

    # ── Appendix: analysis tables (charts stay in the in-app view) ───────
    rendered = appendix.get("analyses_rendered") or []
    if rendered:
        doc.add_heading("Appendix — Computed Analyses", level=1)
        for entry in rendered:
            paragraph = doc.add_paragraph()
            paragraph.add_run(str(entry.get("analysis_type"))).bold = True
            for message in entry.get("messages") or []:
                doc.add_paragraph(str(message), style="List Bullet")
            for table_spec in entry.get("tables") or []:
                columns = table_spec.get("columns") or []
                rows = [
                    [str(row.get(col, "—")) for col in columns]
                    for row in table_spec.get("rows") or []
                ]
                if not rows:
                    continue
                doc.add_paragraph(str(table_spec.get("title") or ""))
                a_table = doc.add_table(rows=1, cols=len(columns))
                a_table.style = "Table Grid"
                for index, column in enumerate(columns):
                    a_table.rows[0].cells[index].text = str(column)
                for row in rows:
                    cells = a_table.add_row().cells
                    for index, value in enumerate(row):
                        cells[index].text = value

    # ── FR5.6 footer info block on every page ────────────────────────────
    doc.sections[0].footer.paragraphs[0].text = footer_text

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


