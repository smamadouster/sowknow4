_MD_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_MD_BOLD_RE = re.compile(r"\*\*(.+?)\*\*")
_MD_ITALIC_RE = re.compile(r"(?<!\w)\*(.+?)\*(?!\w)")
_MD_BULLET_RE = re.compile(r"^\s*[-*+]\s+")


def _md_to_flowables(md: str, styles: dict[str, Any]) -> list[Any]:
    """Minimal markdown → platypus flowables (headings, bullets, paragraphs)."""
    from reportlab.platypus import Paragraph, Spacer
    from reportlab.lib.units import inch

    flowables: list[Any] = []
    for line in (md or "").splitlines():
        stripped = line.strip()
        if not stripped or stripped == "---":
            continue
        heading = _MD_HEADING_RE.match(stripped)
        text = _MD_BOLD_RE.sub(r"<b>\1</b>", stripped)
        text = _MD_ITALIC_RE.sub(r"<i>\1</i>", text)
        if heading:
            flowables.append(Paragraph(text, styles["heading"]))
        elif _MD_BULLET_RE.match(stripped):
            flowables.append(Paragraph("• " + _MD_BULLET_RE.sub("", text), styles["normal"]))
        else:
            flowables.append(Paragraph(text, styles["normal"]))
        flowables.append(Spacer(1, 0.04 * inch))
    return flowables


def _disclosure_text(disclosure: dict[str, Any]) -> str:
    dtype = disclosure.get("type", "disclosure")
    if dtype == "truncation":
        return (
            f"Truncation: {disclosure.get('items_processed')} item(s) processed"
            + (" (result set truncated at the retrieval cap)" if disclosure.get("truncated") else "")
            + f". Ranking rule: {disclosure.get('ranking_rule')}."
        )
    if dtype == "degraded_sources":
        return (
            f"Degraded sources: {len(disclosure.get('failed_queries') or [])} "
            "search call(s) failed permanently; results are partial."
        )
    if dtype == "removed_claims":
        return (
            f"Removed claims: {disclosure.get('count')} statement(s) stripped "
            "from the summary during grounding validation."
        )
    if dtype == "conflicts":
        return (
            f"Conflicts: {disclosure.get('count')} conflicting fact value(s) "
            "resolved by source precedence (see appendix)."
        )
    if dtype == "zero_results":
        return "Zero results: no items matched the confirmed parameters."
    if dtype == "acl_trimming":
        if disclosure.get("shown") and disclosure.get("trimmed_count") is not None:
            return (
                f"Access control: {disclosure.get('trimmed_count')} matching "
                "document(s) excluded by permission trimming."
            )
        return (
            "Access control: some matching documents were excluded by "
            "permission trimming."
        )
    if dtype == "no_summary":
        return f"Summary: {disclosure.get('message', 'insufficient data for summary')}."
    return str(disclosure.get("message") or dtype)


def export_pdf(deliverable: Any, view: dict[str, Any]) -> bytes:
    """FR5.6: PDF bytes for a deliverable view (reportlab, collections.py pattern).

    FR7.2: the view is sanitised first (idempotent — a view from
    ``build_in_app_view`` is already clean) so a raw ``<`` in a title or
    the summary can never reach reportlab's mini-HTML parser as markup.
    """
    view = sanitise_view(view)
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import (
        HRFlowable,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    generated_at = datetime.now(timezone.utc)
    generated_str = generated_at.strftime("%Y-%m-%d %H:%M UTC")
    data_as_of = (view.get("data_as_of") or "unknown")[:10]

    buffer = io.BytesIO()

    footer_text = f"Generated by SOWKNOW Collection · {generated_str} · data as of {data_as_of}"

    def _add_footer(canv, doc):
        canv.saveState()
        canv.setFont("Helvetica", 8)
        canv.setFillColor(colors.HexColor(BRAND_GREY))
        page_width = letter[0]
        footer_y = 0.3 * inch
        canv.drawString(0.75 * inch, footer_y, footer_text)
        canv.drawRightString(page_width - 0.75 * inch, footer_y, f"Page {doc.page}")
        canv.restoreState()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
    )
    base = getSampleStyleSheet()
    brand_blue = colors.HexColor(BRAND_BLUE)
    styles = {
        "title": ParagraphStyle("COTitle", parent=base["Heading1"], fontSize=18, textColor=brand_blue, spaceAfter=6),
        "subtitle": ParagraphStyle("COSubtitle", parent=base["Normal"], fontSize=10, textColor=colors.HexColor(BRAND_GREY), spaceAfter=4),
        "heading": ParagraphStyle("COHeading", parent=base["Heading2"], fontSize=13, textColor=brand_blue, spaceBefore=12, spaceAfter=6),
        "normal": base["Normal"],
        "small": ParagraphStyle("COSmall", parent=base["Normal"], fontSize=9, textColor=colors.HexColor(BRAND_GREY)),
    }

    story: list[Any] = []

    # ── Header: request params summary, timestamps (FR5.6) ───────────────
    story.append(Paragraph("SOWKNOW Collection Deliverable", styles["title"]))
    story.append(Paragraph(
        f"Generated {generated_str} &nbsp;·&nbsp; Data as of {data_as_of}",
        styles["subtitle"],
    ))
    story.append(HRFlowable(width="100%", thickness=1, color=brand_blue, spaceAfter=10))

    appendix = view.get("appendix") or {}
    params_lines = []
    request = appendix.get("request_params")
    if request:
        params_lines.append(f"<b>Request:</b> {request}")
    story.append(Paragraph(
        f"<b>Deliverable v{view.get('version', 1)}</b> &nbsp;·&nbsp; "
        f"{len(view.get('items') or [])} item(s) &nbsp;·&nbsp; "
        "Links are permission-bound (re-checked at navigation).",
        styles["normal"],
    ))
    for line in params_lines:
        story.append(Paragraph(line, styles["normal"]))
    story.append(Spacer(1, 0.15 * inch))

    # ── Disclosures BEFORE the item list (FR5.6) ─────────────────────────
    disclosures = view.get("disclosures") or []
    if disclosures:
        story.append(Paragraph("Disclosures", styles["heading"]))
        for disclosure in disclosures:
            story.append(Paragraph("• " + _disclosure_text(disclosure), styles["normal"]))
        story.append(Spacer(1, 0.1 * inch))

    # ── Summary ──────────────────────────────────────────────────────────
    if view.get("summary_md"):
        story.append(Paragraph("Summary", styles["heading"]))
        story.extend(_md_to_flowables(view["summary_md"], styles))
        story.append(Spacer(1, 0.1 * inch))

    # ── Item list ────────────────────────────────────────────────────────
    items = view.get("items") or []
    if items:
        story.append(Paragraph("Source Items", styles["heading"]))
        table_data = [["#", "Title", "Date", "Annotation"]]
        for item in items:
            title = (item.get("title") or "untitled")[:60]
            date = (item.get("date") or "—")[:10]
            annotation = (item.get("annotation") or "")[:180]
            table_data.append([
                str(item.get("rank_position") or "—"),
                title,
                date,
                annotation,
            ])
        table = Table(
            table_data,
            colWidths=[0.4 * inch, 2.2 * inch, 0.9 * inch, 3.5 * inch],
            repeatRows=1,
        )
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), brand_blue),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 9),
            ("FONTSIZE", (0, 1), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F3F4F6")]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(table)

    # ── Appendix: analysis tables (charts stay in the in-app view) ───────
    rendered = appendix.get("analyses_rendered") or []
    if rendered:
        story.append(Paragraph("Appendix — Computed Analyses", styles["heading"]))
        for entry in rendered:
            story.append(Paragraph(
                f"<b>{entry.get('analysis_type')}</b>", styles["normal"]
            ))
            for message in entry.get("messages") or []:
                story.append(Paragraph(f"• {message}", styles["small"]))
            for table_spec in entry.get("tables") or []:
                columns = table_spec.get("columns") or []
                rows = [
                    [str(row.get(col, "—")) for col in columns]
                    for row in table_spec.get("rows") or []
                ]
                if not rows:
                    continue
                a_table = Table([columns, *rows], repeatRows=1)
                a_table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E5E7EB")),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ]))
                story.append(Spacer(1, 0.05 * inch))
                story.append(a_table)
            story.append(Spacer(1, 0.08 * inch))

    doc.build(story, onFirstPage=_add_footer, onLaterPages=_add_footer)
    return buffer.getvalue()


